import assert from "node:assert/strict";
import { build } from "esbuild";
const compiled=await build({entryPoints:["src/marketplace-amazon-direct-bulk.ts"],bundle:true,format:"esm",platform:"neutral",write:false,logLevel:"silent"});
const {validateDirectAmazonBatch,executeDirectAmazonBatch}=await import("data:text/javascript;base64,"+Buffer.from(compiled.outputFiles[0].text).toString("base64"));
const make=(sku,marketplace="IT")=>({marketplace,sku,ean:"5715793002944",asin:"B0FJT7C3ZN"});
assert.equal(validateDirectAmazonBatch({items:[make("A"),make("A","DE")]}).length,2);
assert.throws(()=>validateDirectAmazonBatch({items:[make("A"),make("A")]}),/duplicate/);
assert.throws(()=>validateDirectAmazonBatch({items:[{...make("A"),stock:5}]}),/invalid/);
assert.throws(()=>validateDirectAmazonBatch({items:[{...make("A"),ean:"5715793002945"}]}),/invalid/);
assert.throws(()=>validateDirectAmazonBatch({items:Array(13).fill(make("A"))}),/size/);
let called=[];
const ok=async x=>{called.push(x.sku);return {ok:true,status:"SELLER_OFFER_CREATED_VERIFIED",offer_created_verified:true,live_write_attempted:true};};
let result=await executeDirectAmazonBatch({items:[make("A"),make("B")]},{},ok);
assert.deepEqual(called,["A","B"]);assert.equal(result.processed,2);assert.equal(result.halted_for_uncertain_write,false);
called=[];
const uncertain=async x=>{called.push(x.sku);return {ok:true,status:"SUBMITTED_AWAITING_SELLER_READBACK",offer_created_verified:false,live_write_attempted:true};};
result=await executeDirectAmazonBatch({items:[make("A"),make("B")]},{},uncertain);
assert.deepEqual(called,["A"]);assert.equal(result.halted_for_uncertain_write,true);
called=[];
const blocked=async x=>{called.push(x.sku);return {ok:false,status:"BLOCKED_CREATE",offer_created_verified:false,live_write_attempted:false};};
result=await executeDirectAmazonBatch({items:[make("A"),make("B")]},{},blocked);
assert.deepEqual(called,["A","B"]);assert.equal(result.halted_for_uncertain_write,false);
called=[];
const exception=async x=>{called.push(x.sku);throw Error("simulated lost ack");};
result=await executeDirectAmazonBatch({items:[make("A"),make("B")]},{},exception);
assert.deepEqual(called,["A"]);assert.equal(result.halted_for_uncertain_write,true);
console.log("Direct Amazon offer batch offline regression passed; no network/provider calls.");
